"""v0.6 lesson expander — much richer + more comedic content per lesson.

Schema produced (overwrites lesson_NN_*.json files in place):

    { game: {...}, schema: "v2",
      questions: [
        { id, interaction:{type,payload}, variations:[{prompt,options:[...]}, x5] },
        ...
      ],
      hints: ... }

Per-lesson budget:
  - 8 kid-friendly TRUE facts
  - 8 absurd-comedic WRONGS
  - 2 hand-written silly SCENARIO questions
  - 8 question frames (was 5): what-is, true-fact, spot-the-lie,
    bytey-says, good-rule, fill-blank, silly-claim, would-happen
  - 7 paraphrase prefixes

Lessons 11-16 ('in-depth' tool profiles) are upgraded to use the new
history-scene mini-game as their Q1 interaction so the kid watches a
hand-animated story before each question pool. Scene keys must be
defined in HistoryScenes._renderInitial / _frame in index.html.

Idempotent. Re-runs produce identical files.
"""
