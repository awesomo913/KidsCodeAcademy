def _shuffled(seq: list[Any], salt: int) -> list[Any]:
    out = seq.copy()
    random.Random(salt).shuffle(out)
    return out


def _pick_n(seq: list[str], n: int, salt: int) -> list[str]:
    pool = _shuffled(seq, salt)
    if n <= len(pool):
        return pool[:n]
    extra = _shuffled(GENERIC_ABSURD, salt + 7)[: n - len(pool)]
    return pool + extra


def _build_variation(frame: dict[str, Any], paraphrase: str, seed: dict[str, Any],
                     variation_idx: int, question_idx: int) -> dict[str, Any]:
    salt = (question_idx + 1) * 100 + variation_idx
    facts = seed["facts"]
    wrongs = seed["wrongs"]
    prompt = paraphrase + frame["prompt"].format(concept=seed["concept"])
    # Stride by 3 so qi/v cross-product doesn't collide within 10 variations
    if frame["pick_truth"]:
        correct_text = facts[(variation_idx + question_idx * 3) % len(facts)]
        wrong_texts = _pick_n(wrongs, 3, salt)
    else:
        correct_text = wrongs[(variation_idx + question_idx * 3) % len(wrongs)]
        wrong_texts = _pick_n(facts, 3, salt)
    options = [{"text": correct_text, "correct": True}]
    options.extend({"text": t, "correct": False} for t in wrong_texts)
    options = _shuffled(options, salt + 13)
    return {"prompt": prompt, "options": options}


def _assert_no_dupes(variations: list[dict[str, Any]], qid: str) -> None:
    """Fail loud if two variations share the same prompt OR same correct text."""
    seen_prompts = set()
    seen_correct = set()
    for v in variations:
        p = v.get("prompt", "")
        c_text = next((o["text"] for o in v.get("options", []) if o.get("correct")), "")
        if p in seen_prompts:
            raise ValueError(f"{qid}: duplicate prompt across variations: {p!r}")
        if c_text in seen_correct:
            raise ValueError(f"{qid}: duplicate correct-answer across variations: {c_text!r}")
        seen_prompts.add(p)
        seen_correct.add(c_text)


_SCENARIO_REFRAMES: list[str] = [
    "{p}",
    "Imagine: {p}",
    "Help Bytey decide — {p}",
    "Picture this: {p}",
    "Tricky one — {p}",
]


def _scenario_to_variations(scenario: dict[str, Any], salt: int) -> list[dict[str, Any]]:
    """Convert ONE hand-written scenario into VARIATIONS_PER_QUESTION variations.

    Uses two layers:
      - layer 1 (v < 11): paraphrase prefix only (existing pattern)
      - layer 2 (v >= 11 OR fallback): SCENARIO_REFRAMES wrap the prompt itself
    Within 10 variations, cycle through both layers to ensure unique prompts.
    """
    out = []
    base = scenario["prompt"]
    for v in range(VARIATIONS_PER_QUESTION):
        if v < len(PARAPHRASES):
            prompt = PARAPHRASES[v] + base
        else:
            reframe = _SCENARIO_REFRAMES[(v - len(PARAPHRASES)) % len(_SCENARIO_REFRAMES)]
            prompt = reframe.format(p=base)
        opts = _shuffled(scenario["options"], salt + v * 17)
        out.append({"prompt": prompt, "options": [dict(o) for o in opts]})
    return out


def _gate(word: str) -> dict[str, Any]:
    """Type-this-word gate template — every gate teaches typing across the curriculum."""
    word = word.upper()
    return {
        "type": "type-this-word",
        "payload": {
            "prompt": f"Type {word} and press Send to keep going!",
            "target_display": word,
            "targets": [word.lower()],
            "hint_wrong": f"Type the word {word} (any case is fine).",
        },
    }


# Curated word pool rotated through gate slots. Mix of 2-5 letter words.
GATE_TEMPLATES: list[dict[str, Any]] = [
    _gate("GO"), _gate("YES"), _gate("FUN"), _gate("COOL"), _gate("NEXT"),
    _gate("WIN"), _gate("PLAY"), _gate("CODE"), _gate("OK"), _gate("JUMP"),
]


def _question_count(lesson_id: int) -> int:
    """5-8 questions per lesson, deterministic from id."""
    return 5 + (lesson_id % 4)


def _build_questions(lesson: dict[str, Any], seed: dict[str, Any]) -> list[dict[str, Any]]:
    n = _question_count(lesson["id"])
    questions: list[dict[str, Any]] = []

    # Q1 — original lesson.game as gate (or history-scene override for lessons 11-16)
    q1_interaction = HISTORY_OVERRIDES.get(lesson["id"]) or lesson.get("game") or GATE_TEMPLATES[0]
    q1_variations = [
        _build_variation(FRAMES[v % len(FRAMES)], PARAPHRASES[v % len(PARAPHRASES)], seed, v, 0)
        for v in range(VARIATIONS_PER_QUESTION)
    ]
    _assert_no_dupes(q1_variations, "q1")
    questions.append({"id": "q1", "interaction": q1_interaction, "variations": q1_variations})

    scenarios = list(seed.get("scenarios") or [])
    if scenarios:
        sc = scenarios.pop(0)
        questions.append({
            "id": "q2",
            "interaction": GATE_TEMPLATES[1 % len(GATE_TEMPLATES)],
            "variations": _scenario_to_variations(sc, salt=1000 + lesson["id"]),
        })

    frame_cycle = ["spot_lie", "true_fact", "silly_claim", "good_rule", "fill_blank", "would_happen", "best_say",
                   "silly_vs_real", "bytey_confused", "tell_grandma", "find_truth", "robot_says", "which_helps"]
    fi = 0
    qi = len(questions)
    while qi < n:
        if scenarios and qi % 3 == 2:
            sc = scenarios.pop(0)
            questions.append({
                "id": f"q{qi + 1}",
                "interaction": GATE_TEMPLATES[qi % len(GATE_TEMPLATES)],
                "variations": _scenario_to_variations(sc, salt=2000 + lesson["id"] * 10 + qi),
            })
        else:
            key = frame_cycle[fi % len(frame_cycle)]
            frame = next(f for f in FRAMES if f["key"] == key)
            fi += 1
            qid = f"q{qi + 1}"
            qvars = [
                _build_variation(frame, PARAPHRASES[(v + qi) % len(PARAPHRASES)], seed, v, qi)
                for v in range(VARIATIONS_PER_QUESTION)
            ]
            _assert_no_dupes(qvars, qid)
            questions.append({
                "id": qid,
                "interaction": GATE_TEMPLATES[qi % len(GATE_TEMPLATES)],
                "variations": qvars,
            })
        qi += 1

    return questions


def expand_lesson(path: Path) -> bool:
    lesson: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    lesson_id = int(lesson.get("id") or 0)
    seed = SEEDS.get(lesson_id)
    if seed is None:
        log.warning("no seed for lesson %d (%s); leaving alone", lesson_id, path.name)
        return False

    # v0.7.1: capture existing _audio paths keyed by (qid, vidx) so we can
    # restore them after rebuilding `questions[]`. Otherwise running this
    # generator wipes every prebaked-prompt path forcing a re-bake.
    prior_audio: dict[tuple[str, int], str] = {}
    for q in (lesson.get("questions") or []):
        qid = str(q.get("id") or "")
        for vidx, v in enumerate(q.get("variations") or []):
            audio = v.get("_audio")
            if audio:
                prior_audio[(qid, vidx)] = audio

    # Lessons 11-16: also patch the top-level lesson.game so the lesson list
    # widgets / future migrations see the new history-scene as the demo.
    if lesson_id in HISTORY_OVERRIDES:
        lesson["game"] = HISTORY_OVERRIDES[lesson_id]

    lesson["questions"] = _build_questions(lesson, seed)
    lesson["schema"] = "v2"

    # Restore prior _audio paths where the (qid, vidx) shape matches.
    if prior_audio:
        for q in lesson["questions"]:
            qid = str(q.get("id") or "")
            for vidx, v in enumerate(q.get("variations") or []):
                key = (qid, vidx)
                if key in prior_audio:
                    v["_audio"] = prior_audio[key]

    path.write_text(json.dumps(lesson, indent=2, ensure_ascii=False), encoding="utf-8")
    log.info("expanded %s -- %d questions x %d variations",
             path.name, len(lesson["questions"]), len(lesson["questions"][0]["variations"]))
    return True


def main() -> int:
    files = sorted(LESSONS_DIR.glob("lesson_*.json"))
    if not files:
        log.error("no lesson files at %s", LESSONS_DIR)
        return 1
    ok = 0
    for f in files:
        try:
            if expand_lesson(f):
                ok += 1
        except Exception as exc:  # noqa: BLE001
            log.exception("FAIL %s: %s", f.name, exc)
    log.info("DONE -- %d expanded", ok)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
