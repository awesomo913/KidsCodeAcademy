def _S(concept: str, facts: list[str], wrongs: list[str], scenarios: list[dict]) -> dict:
    return {"concept": concept, "facts": facts, "wrongs": wrongs, "scenarios": scenarios}


def _scn(prompt: str, opts: list[tuple[str, bool]]) -> dict:
    return {"prompt": prompt, "options": [{"text": t, "correct": c} for t, c in opts]}


